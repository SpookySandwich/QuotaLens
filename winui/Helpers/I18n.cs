    public static Lang Current { get; } = DetectLang();

    private static Lang DetectLang()
    {
        try
        {
            var name = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
            return name.StartsWith("zh", StringComparison.OrdinalIgnoreCase) ? Lang.Zh : Lang.En;
        }
        catch
        {
            return Lang.En;
        }
    }

    private static Dictionary<string, string> Table => Current == Lang.Zh ? Zh : En;

    public static string T(string key, IReadOnlyDictionary<string, string>? vars = null)
    {
        if (!Table.TryGetValue(key, out var text))
            text = En.TryGetValue(key, out var fallback) ? fallback : key;

        if (vars != null)
            foreach (var (k, v) in vars)
                text = text.Replace("{" + k + "}", v);

        return text;
    }

    public static string T(string key, string varName, string varValue) =>
        T(key, new Dictionary<string, string> { [varName] = varValue });
}
